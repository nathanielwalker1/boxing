// Writes docs/anim/MOCAP_INVENTORY.md from the classified rows. Regenerated on every run; do not hand-edit.
import { writeFileSync } from 'node:fs';

// The game's needs. Each matches clip labels (exact, or prefix with '*'); punch needs also search the
// punches found inside any clip (combos count when a single punch can be cut out).
const NEEDS = [
  ['Fight idle (bouncy, guard up)', ['fight idle*']],
  ['Jab', [], 'jab'], ['Cross', [], 'cross'],
  ['Lead hook', [], 'lead hook'], ['Rear hook', [], 'rear hook'],
  ['Lead uppercut', [], 'lead uppercut'], ['Rear uppercut', [], 'rear uppercut'],
  ['Body jab', [], 'body jab'], ['Body cross', [], 'body cross'], ['Body hook', [], 'body * hook'],
  ['High guard block (held)', ['block']], ['Blocked-punch reaction', ['block reaction']],
  ['Hit reaction: head light', ['hit head light']], ['Hit reaction: head medium', ['hit head medium']],
  ['Hit reaction: head heavy', ['hit head heavy']], ['Hit reaction: body', ['hit body']],
  ['Hit reaction: uppercut', ['hit uppercut*']],
  ['Step forward', ['step forward']], ['Step back', ['step back']], ['Step left', ['step left']], ['Step right', ['step right']],
  ['Pivots', ['pivot*']],
  ['Slip left', ['slip left', 'slips']], ['Slip right', ['slip right', 'slips']], ['Duck', ['duck', 'slips']], ['Lean back', ['lean back']],
  ['Stagger / stunned', ['stagger*', 'hit uppercut heavy (staggers back)']],
  ['Knockdown fall', ['knockdown fall', 'knockdown and get up']], ['Down (on the canvas)', ['down']], ['Get up (from lying)', ['get up']],
  ['Win', ['win']], ['Lose', ['lose']], ['Walk to corner', ['walk*', 'entry (walk in)']],
];

const match = (label, pats) => pats.some((p) => (p.endsWith('*') ? label.startsWith(p.slice(0, -1)) : label === p));
const punchMatch = (type, want) => (want.includes('*') ? new RegExp('^' + want.replace('*', '.*') + '$').test(type) : type === want);

export function writeInventory(path, rows, roles = {}) {
  const live = rows.filter((r) => !r.dupOf && !r.usable.startsWith('no'));
  const L = [];
  L.push('# Mocap inventory (generated)', '');
  L.push('Generated by `npm run mocap` (tools/mocap/run.mjs) from the Mixamo FBX folder. Do not hand-edit:');
  L.push('fix a label in `tools/mocap/classify.mjs` or `tools/mocap/overrides.json` and re-run.');
  L.push('Contact sheets: `scripts/output/mocap_sheets/`. Raw data: `.cache/mocap/raw/<slug>.json` (format in `tools/mocap/extract.py`).');
  L.push('Stance is from the feet (left foot forward = orthodox). "Travel" is the hips\' horizontal path (net / peak, metres).');
  L.push('Loop = first and last pose within 6 deg mean bone rotation and 10 cm hips. Mirroring is ours, so one side covers both.', '');
  L.push('| slug | file | s | label | stance | travel | loop | usable | note |');
  L.push('|---|---|---|---|---|---|---|---|---|');
  for (const r of rows) {
    const s = r.stats;
    const travel = r.inPlace ? `in place (${s.peakTravel})` : s.netTravel < 0.1 ? `lunges ${s.peakTravel} and returns` : `${s.travelDir} ${s.netTravel} / ${s.peakTravel}`;
    const usable = r.dupOf ? `no (duplicate of ${r.dupOf})` : r.usable;
    const extra = (r.mirrorOf ? ` Mirror of ${r.mirrorOf}.` : '') + (r.similarTo ? ` Near-duplicate of ${r.similarTo} (${r.similarD} cm).` : '');
    L.push(`| ${r.slug} | ${r.file} | ${s.seconds} | ${r.label} | ${s.stance} | ${travel} | ${r.loop ? 'yes' : 'no'} | ${usable} | ${r.note.replace(/\|/g, '/')}${extra} |`);
  }
  L.push('', '## Usable for', '');
  const gaps = [];
  for (const [need, pats, punch] of NEEDS) {
    const hits = [];
    for (const r of live) {
      if (pats.length && match(r.label, pats)) hits.push(`${r.slug}`);
      if (punch) {
        // punches found inside a clip count only when the clip is a punch clip (not a hit reaction whose arms flail)
        const isPunchClip = r.label.startsWith('combo') || r.punches.some((p) => p.type === r.label);
        const ps = isPunchClip ? r.punches.filter((p) => punchMatch(p.type, punch)) : [];
        if (!ps.length && punchMatch(r.label, punch)) hits.unshift(`${r.slug} (single, override)`);
        else if (ps.length && r.punches.length === 1) hits.unshift(`${r.slug} (single)`);
        else for (const p of ps.slice(0, 2)) hits.push(`${r.slug} f${p.from}-${p.to}`);
      }
    }
    if (!hits.length) gaps.push(need);
    L.push(`- **${need}:** ${hits.length ? hits.slice(0, 5).join(', ') : '_none_'}`);
  }
  L.push('', '## Roles (public/fighter/clips/roles.json, what the game plays)', '');
  for (const [k, v] of Object.entries(roles)) {
    const extra = v ? [v.contact !== undefined ? `contact f${v.contact}` : '', v.impact != null ? `impact f${v.impact}` : '', v.settle !== undefined ? `settles f${v.settle}` : '', v.body ? 'BODY-LEVEL stand-in' : ''].filter(Boolean).join(', ') : '';
    L.push(`- **${k}:** ${v ? `${v.slug} f${v.from}-${v.to}${extra ? ' (' + extra + ')' : ''}` : '_none_'}`);
  }
  L.push('', '## Gaps', '');
  for (const g of gaps) L.push(`- ${g}`);
  for (const [k, v] of Object.entries(roles)) {
    if (v === null) L.push(`- role ${k}: no clip${k === 'slip_left' ? ' (mirror slip_right)' : ''}`);
    else if (v.body) L.push(`- role ${k}: no head-level clip; the body-level ${v.slug} stands in`);
  }
  const dups = rows.filter((r) => r.dupOf || r.mirrorOf || r.similarTo);
  L.push('', '## Duplicates and mirrors', '');
  L.push('Exact = same frames within 1 cm; mirror = left/right swapped within 2 cm; near = same shape after time-normalising and removing travel (mean bone gap in cm).', '');
  for (const r of dups) L.push(`- ${r.slug}: ${r.dupOf ? 'exact duplicate of ' + r.dupOf : r.mirrorOf ? 'mirror of ' + r.mirrorOf : `near-duplicate of ${r.similarTo} (${r.similarD} cm)`}`);
  if (!dups.length) L.push('- none');
  writeFileSync(path, L.join('\n') + '\n');
}
